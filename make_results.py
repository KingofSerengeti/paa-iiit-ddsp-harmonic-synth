def pivot(rs, rowkey, colkey, valkey, rowname):
    rk = list(dict.fromkeys(r[rowkey] for r in rs)); ck = list(dict.fromkeys(r[colkey] for r in rs))
    v = {(r[rowkey], r[colkey]): r[valkey] for r in rs}
    out = ["| " + rowname + " | " + " | ".join(ck) + " |", "|" + "---|" * (len(ck) + 1)]
    out += ["| " + a + " | " + " | ".join(v.get((a, c), "") for c in ck) + " |" for a in rk]
    return "\n".join(out) + "\n"


