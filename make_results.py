"""Regenerate RESULTS.md from the CSVs and logs in this folder (no numbers are typed by hand).
Run:  python make_results.py"""
import csv, re, subprocess
import torch

MAIN = ("8", "100", "64000")


def rows(path, filt=lambda r: True):
    return [r for r in csv.DictReader(open(path)) if filt(r)]


def table(path, filt=lambda r: True, cols=None):
    rs = rows(path, filt)
    cols = cols or list(rs[0].keys())
    out = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    out += ["| " + " | ".join(r[c] for c in cols) + " |" for r in rs]
    return "\n".join(out) + "\n"


def get(path, impl, cfg=MAIN, key="ms_med"):
    for r in rows(path):
        if r["impl"] == impl and (r["B"], r["K"], r["T"]) == cfg:
            return float(r[key])
    raise KeyError(impl)


main = lambda r: (r["B"], r["K"], r["T"]) == MAIN
nvcc = re.search(r"release [^\n]*", subprocess.run(["nvcc", "--version"], capture_output=True, text=True).stdout).group(0)
drv = subprocess.run(["nvidia-smi", "--query-gpu=driver_version", "--format=csv,noheader"], capture_output=True, text=True).stdout.strip()

# Derived arithmetic (main config). Minimum DRAM bytes, not measured traffic.
B, K, T, F = 8, 100, 64000, 1000
fused_bytes = B * F * K * 4 + B * F * (4 + 4 + 8) + B * T * 4       # dist + f0/amp/phi read once, output written once
table_bytes = B * T * K * 4                                          # one [B,T,K] fp32 table
kern_ms = get("runs_summary.csv", "fused_kernel_only")
comp_ms = get("runs_summary.csv", "faithful_angular_compile")
PEAK = 672.0                                                         # GB/s, published RTX 5070 spec (192-bit GDDR7, 28 Gbps)
fused_gbs = fused_bytes / (kern_ms * 1e-3) / 1e9
comp_gbs = 2 * table_bytes / (comp_ms * 1e-3) / 1e9                  # table written once and read once (lower bound)

summ_cols = ["impl", "B", "K", "T", "runs", "ms_med", "ms_min", "ms_max", "mJ_med", "mJ_min", "mJ_max", "peak_extra_MB", "rel_l2_err"]
sweep_cols = ["f0_range", "impl", "active_harmonic_frac", "ms_median", "ms_std", "energy_mJ", "energy_std", "max_abs_err_vs_fp64", "rel_l2_err"]
abl_cols = ["impl", "B", "K", "T", "ms_median", "ms_std", "energy_mJ", "energy_std", "max_abs_err_vs_fp64", "rel_l2_err"]
prof = open("torch_profile_fused.txt").read()
prof = "\n".join(l for l in prof.splitlines() if not l.startswith(("/", "  _warn_once")))

